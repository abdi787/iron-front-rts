#!/usr/bin/env node
/**
 * IRON FRONT — Map Validator & Built-in Registry Sync CLI
 *
 * Usage:
 *   node scripts/validate_maps.mjs                       # Validate all maps in maps/manifest.json
 *   node scripts/validate_maps.mjs maps/my_map.json ...  # Validate specific map JSON file(s)
 *   node scripts/validate_maps.mjs --sync-builtin        # Validate all manifest maps and regenerate js/maps_builtin.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const require = createRequire(import.meta.url);
const MAPS = require(path.join(ROOT, 'js', 'maps.js'));

const args = process.argv.slice(2);
const syncBuiltin = args.includes('--sync-builtin');
const fileArgs = args.filter((a) => !a.startsWith('--'));

let targets = [];
if (fileArgs.length > 0) {
  targets = fileArgs.map((f) => path.resolve(process.cwd(), f));
} else {
  const manifestPath = path.join(ROOT, 'maps', 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const entries = Array.isArray(manifest) ? manifest : (manifest.maps || []);
  targets = entries.map((e) => path.join(ROOT, 'maps', typeof e === 'string' ? e : e.file));
}

let hasErrors = false;
const parsedMaps = [];

for (const filePath of targets) {
  const rel = path.relative(ROOT, filePath);
  let raw;
  try {
    raw = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (err) {
    console.error(`[FAIL] ${rel}: Invalid JSON — ${err.message}`);
    hasErrors = true;
    continue;
  }

  const res = MAPS.validateMap(raw);
  const st = res.stats;
  const tag = res.ok ? (res.warnings.length ? 'WARN' : 'OK  ') : 'FAIL';
  const summary = st
    ? `${st.worldW}x${st.worldH} ${st.biome} | HQ dist=${st.hqDistance}u | Sup=${st.totalSupplies} (P:${st.playerNearSupplies} E:${st.enemyNearSupplies}) | Outposts=${st.capturePointCount} | Rocks=${st.obstacleCount} | BuildSlots=${st.playerBuildSpots}/${st.enemyBuildSpots}`
    : 'no stats';
  console.log(`[${tag}] ${rel} (${raw.id || '?'}) — ${summary}`);

  for (const e of res.errors) {
    const loc = e.x !== undefined ? ` @(${Math.round(e.x)},${Math.round(e.y)})` : '';
    console.error(`       ERROR [${e.code}]${loc}: ${e.message}`);
  }
  for (const w of res.warnings) {
    const loc = w.x !== undefined ? ` @(${Math.round(w.x)},${Math.round(w.y)})` : '';
    console.warn(`       WARN  [${w.code}]${loc}: ${w.message}`);
  }

  if (!res.ok) hasErrors = true;
  else parsedMaps.push(raw);
}

if (hasErrors) {
  console.error('\nMap validation failed.');
  process.exit(1);
}

if (syncBuiltin && fileArgs.length === 0) {
  const outPath = path.join(ROOT, 'js', 'maps_builtin.js');
  const body = [
    '// AUTO-GENERATED by `node scripts/validate_maps.mjs --sync-builtin` from maps/manifest.json',
    '// Provides zero-latency startup and offline file:// fallback; HTTP/Pages also loads maps/manifest.json.',
    '(() => {',
    "  'use strict';",
    '  const FL = (window.FRONTLINE = window.FRONTLINE || {});',
    '  if (!FL.MAPS) return;',
    `  FL.MAPS.registerBuiltinMaps(${JSON.stringify(parsedMaps, null, 2)});`,
    '})();',
    ''
  ].join('\n');
  fs.writeFileSync(outPath, body, 'utf8');
  console.log(`\nSynced ${parsedMaps.length} built-in map(s) -> ${path.relative(ROOT, outPath)}`);
}
